// 목록 카드용: 마크다운 기호를 벗겨 "읽히는 평문"으로 요약. (완벽한 파서가 아니라 프리뷰용)
export function toPlainPreview(md: string): string {
  return md
    .replace(/```[\s\S]*?```/g, ' ')            // 코드블록 통째 제거
    .replace(/`([^`]+)`/g, '$1')                // 인라인 코드 → 내용만
    .replace(/^#{1,6}\s+/gm, '')                // ## 헤딩 마커
    .replace(/^\s*>\s?/gm, '')                  // > 인용 마커
    .replace(/^\s*[-*+]\s+/gm, '')              // - 리스트 불릿
    .replace(/^\s*\d+\.\s+/gm, '')              // 1. 번호 리스트
    .replace(/!\[([^\]]*)\]\([^)]*\)/g, '$1')   // 이미지 → alt 텍스트
    .replace(/\[([^\]]+)\]\([^)]*\)/g, '$1')    // 링크 → 표시 텍스트
    .replace(/(\*\*|__)(.*?)\1/g, '$2')         // **볼드**
    .replace(/(\*|_)(.*?)\1/g, '$2')            // *이탤릭*
    .replace(/~~(.*?)~~/g, '$1')                // ~~취소선~~
    .replace(/\n{2,}/g, '\n')                   // 빈 줄 축소
    .trim()
}
